// ============================================================
// Lab 01 · LED 闪烁 — 你的第一个 FPGA 电路
// ============================================================
// 心智模型:这不是"程序",是一张电路图:
//   一个 24 位计数器(2^24 个时钟翻转一次输出位)
//   + 一根从计数器最高位引到 LED 引脚的导线
//
// 计数器第 N 位输出方波频率 = 时钟÷2^(N+1):bit23 → 50M/2^24 ≈ 2.98Hz
// (LED 亮 0.168s、灭 0.168s,即以约 3Hz 闪烁;想更慢就用更低位的倍数,如 cnt[25]→0.75Hz)
//
// 端口 = 这块电路对外伸出的"引脚",名字要和约束文件 .xdc 对应
module led_blink (
    input  wire clk,    // 50MHz 晶振进来(N18)
    input  wire rst_n,  // PL 按键,按下为 0(P14)
    output wire led     // LED 输出(R14)
);

    // reg = 寄存器(时序电路的细胞);always @(posedge clk) = 每个时钟上升沿执行一次
    // 翻译成电路:一排 D 触发器,每个时钟节拍把计数+1 的结果存进去
    reg [23:0] cnt;

    always @(posedge clk) begin
        if (!rst_n)              // 按键按下:异步清零(复习:这就是"复位"的电路形态)
            cnt <= 24'd0;        // <= 是"非阻塞赋值":时序电路的标准写法,先记规则后细究
        else
            cnt <= cnt + 1'd1;   // 每个 clk 上升沿,计数器+1(2^24 计满自动回绕)
    end

    // assign = "永久接线":LED 的正极永远连着计数器的第 23 位
    // (它随计数自然翻转,不需要任何"代码"去驱动——这就是电路!)
    assign led = cnt[23];

endmodule

// ============================================================
// Lab 03 · CDC 撕裂演示 — 二进制 vs 格雷码 双计数器
// ============================================================
// 这块电路故意"裸奔":一个 4 位二进制计数器和一个 4 位格雷码
// 计数器,双双活在 clk_src 时钟域,输出直接拉出去给另一个
// 时钟域(clk_dst,在 tb 里)采样——中间不做任何防护。
//
//   二进制版:7(0111)→8(1000) 时 4 位同时翻转。真实芯片里
//             各位的布线延迟不等,到达采样端有先有后 → 数值撕裂。
//   格雷码版:相邻数值只差 1 位,任一时刻最多 1 位在"路上"
//             → 采样值永远是一个合法计数值,撕裂免疫。
//
// pace 说明:计数器每 2 拍才 +1(不是每拍)。这让相邻两次
// 变化隔开 40ns,远大于各位延迟差(3ns)——"撕裂"才不会和
// "连续采样正常跳数"混在一起,检测器的判据才是干净的一条:
// 两个相邻样本的值,要么相等,要么恰好 +1。
//
// 注意:本模块只用于仿真教学(撕裂由 tb 显式注入延迟来演示);
// 板上跑的是"正确链"(lab02_v2 两级同步器),见 README。
module tear_demo (
    input  wire       clk_src,   // 源时钟域:两个计数器活在这里
    output reg  [3:0] bin_q,     // 二进制计数输出(未防护,等着被撕)
    output reg  [3:0] gray_q     // 格雷码计数输出(对照品)
);

    // 格雷码(Gray Code)变换:二进制右移 1 位后与自身异或。
    // 性质:相邻两个数值的格雷码恰好只差 1 位——这是它的全部魔法。
    wire [3:0] bin_gray = (bin_q >> 1) ^ bin_q;

    // pace:每 2 拍产一个递增使能(计数节奏放慢一半)
    reg pace = 1'b0;
    always @(posedge clk_src) pace <= ~pace;

    // 仿真教具,直接给初值(上板电路请像 lab01 那样接 rst_n)
    initial begin
        bin_q  = 4'd0;
        gray_q = 4'd0;
    end

    always @(posedge clk_src) begin
        if (pace) begin
            bin_q  <= bin_q + 1'd1;   // 0,1,2,...,15,0,...
            gray_q <= bin_gray;       // 跟着 bin_q 走,每步恰好翻 1 位
        end
    end

endmodule

// ============================================================
// Lab 02 · 裸版对比实验 — "不过滤"的按键翻转(先烧我,先看乱翻!)
// ============================================================
// 这 ~20 行故意"裸奔":检测到按下沿就翻转 LED,既不消抖,也不同步。
// 现象:按一次,LED 可能翻 0 / 1 / 2 次——乱翻,且每次不一样。
// 快速轻按最容易复现。它是 ch02 的"证物 A",别改它,烧上去感受混乱。
module key_toggle_raw (
    input  wire clk,     // 50MHz 晶振(N18)
    input  wire key,     // PL_KEY(P14,按下 = 0)
    output reg  led      // LED(R14,低 = 亮)
);

    // 给输入拍一张"上一拍照片"——边沿检测的材料(和参考实现同一个惯用法)
    reg key_q;
    always @(posedge clk) key_q <= key;

    // 按下沿:上一拍是 1(松开)、这一拍是 0(按下)→ 这一拍输出 1
    // 裸版之"裸":金属片每弹一次,这里就出一个脉冲,全放行
    wire press = key_q & ~key;

    // T 触发器:每来一个脉冲,LED 翻转一次(脉冲有几个,就翻几次)
    always @(posedge clk) begin
        if (press)
            led <= ~led;
    end

endmodule

// ============================================================
// Lab 01 测试台(Testbench, TB)— 第 1 章仿真入门用
// ============================================================
// 测试台不是电路:它是"写给仿真器的软件",永远不会被综合成硬件。
// 三件事:① 造时钟  ② 造激励  ③ 说停($finish)。
// 放文件的规矩:它属于 Vivado 工程的 Simulation Sources 筐,不是 Design Sources。
`timescale 1ns/1ps          // 时间单位 1ns(#10 = 10ns),最小刻度 1ps

module tb_led_blink;        // 测试台没有端口——它包住被测电路,自己就是顶层

    reg  clk   = 1'b0;      // 造时钟用的"拨动开关"(reg 在测试台里=我们熟悉的变量)
    reg  rst_n = 1'b0;      // 按键:先按住(0=按下),让计数器清零起步,稍后松手
    wire led;               // 接被测电路输出:一根"观察用导线",光看不驱动

    // ---------- 被测电路(DUT)----------
    // "模块例化":把 led_blink 这块已知电路摆进测试台,引脚按名字接上
    led_blink dut (
        .clk   (clk),       // 假晶振 → 电路的 clk(板上是 N18,仿真里是我们造的)
        .rst_n (rst_n),     // 激励 → 电路的按键(板上是 P14,仿真里是 reg)
        .led   (led)        // 电路输出 → 观察线(板上是 R14,仿真里进波形)
    );

    // ---------- 要素 ①:造时钟 ----------
    // 每 10ns 翻转一次 = 周期 20ns = 50MHz,与板上 N18 晶振同款
    always #10 clk = ~clk;

    // ---------- 要素 ②:造激励 + 要素 ③:说停 ----------
    initial begin
        repeat (20) @(posedge clk);   // 按住复位 20 拍:确保计数器从 0 干净起步
        rst_n = 1'b1;                 // 松开按键(1=松开),电路开始自由奔跑
        repeat (200) @(posedge clk);  // 再跑 200 拍:cnt 低位的翻转规律尽收眼底
        $finish;                      // 收工:测试台不喊停,仿真器会永远演下去
    end

endmodule
